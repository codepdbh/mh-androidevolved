"""Lift boot phase 2: the CRT start-up steps of the real entry point and all 98 C++ static initialisers.

The CRT entry 0x64a380 (reached only from the protection wrapper) calls
0x653460(0x7eba68) and the CRT initialisation 0x655490 before walking .CRT; the
unit translates those two steps and every initialiser, with x87 admitted through
the audited rewrites of recomp_lift. The header stub 0x400080 is provided by the
runtime (runtime/protection_redirect.c), never translated.

Closure: the functions that really run, from the x86 trace of the same boot
(tools/trace_static_init_x86.py, which must have completed every step). Starting
at the roots, a function with at least one executed instruction is translated
and its direct calls followed; one with none becomes a fail-closed stop. Executed
code not inside any translated function (targets of indirect calls through
vtables or code pointers) is added as further roots until everything executed is
covered. Every translated function must pass the audit. Also writes a private
header with the run order and the executable's size and CRC-32.
"""
import hashlib,json,sys,zlib
import pefile
from recomp_lift import lift_closure,_tools
from inspect_entrypoint import ROOT,GAME,EXPECTED
STARTUP=[(0x653460,(0x7eba68,)),(0x655490,())]
HEADER_STUB,PRUS_SLOT=0x400080,0x850000
APIS=['EnterCriticalSection','LeaveCriticalSection','InitializeCriticalSection','DeleteCriticalSection','GlobalAlloc','GlobalFree',
      'TlsAlloc','TlsFree','TlsGetValue','TlsSetValue','GetStdHandle','GetCurrentProcess','DuplicateHandle','GetCommandLineA',
      'GetEnvironmentStrings','FreeEnvironmentStringsA','CreateEventA','GetTickCount','ExitProcess','MessageBoxA']
def executed_closure(data,roots):
    trace=json.loads((ROOT/'private/analysis/static_init/trace.json').read_text(encoding='utf-8'))
    if trace['input_sha256']!=EXPECTED or trace['error'] or len(trace['completed'])!=len(STARTUP)+98:
        raise SystemExit('the x86 trace of boot phase 2 is missing or incomplete; run tools/trace_static_init_x86.py')
    executed={int(b,16) for b in trace['executed_blocks']}
    analyze_pe,build_iat_map,Disassembler,_=_tools()
    info=analyze_pe(str(GAME));iat=build_iat_map(info);dis=Disassembler(data,info.image_base,info.sections)
    kept,stopped,code={}, set(), {}
    def instructions(address):
        if address not in code:
            f=dis.disassemble_function(address,iat)
            code[address]=(f,{i.address for b in f.blocks.values() for i in b.instructions} if f else set())
        return code[address]
    pending=list(roots)
    while True:
        while pending:
            a=pending.pop(0)
            if a in kept or a in stopped or a==HEADER_STUB:continue
            f,ins=instructions(a)
            if not f:raise SystemExit(f'no function at {a:#x}')
            if not ins&executed:stopped.add(a);continue
            kept[a]=ins;pending.extend(sorted(f.calls_to))
        covered=set().union(*kept.values())
        uncovered=sorted(b for b in executed if 0x401000<=b<0x66e200 and b not in covered)
        if not uncovered:break
        f,ins=instructions(uncovered[0])
        if not f or uncovered[0] not in ins:raise SystemExit(f'executed code at {uncovered[0]:#x} is not a function entry')
        stopped.discard(uncovered[0]);pending.append(uncovered[0])
    return sorted(kept),stopped
def main():
    data=GAME.read_bytes();pe=pefile.PE(data=data)
    if hashlib.sha256(data).hexdigest()!=EXPECTED:raise SystemExit('unexpected executable hash')
    slots={(imp.name or b'').decode():imp.address for e in pe.DIRECTORY_ENTRY_IMPORT for imp in e.imports}
    missing=[a for a in APIS if a not in slots]
    if missing:raise SystemExit(f'imports not found: {missing}')
    crt=[s for s in pe.sections if s.Name.rstrip(b'\0')==b'.CRT'][0];raw=crt.get_data()[:crt.Misc_VirtualSize]
    inits=[p for p in (int.from_bytes(raw[i:i+4],'little') for i in range(0,len(raw)//4*4,4)) if p]
    if len(inits)!=98:raise SystemExit(f'unexpected initialiser count {len(inits)}')
    kept,stopped=executed_closure(data,[a for a,_ in STARTUP]+inits)
    print(len(kept),'executed functions to translate;',len(stopped),'never-executed callees become fail-closed stops')
    report=lift_closure(kept,stopped|{HEADER_STUB},{slots[a] for a in APIS},'boot_phase2',max_functions=len(kept)+1,indirect=True,
                        auto_stop=False,x87=True,provided={HEADER_STUB},dispatch_slots={PRUS_SLOT})
    runs=STARTUP+[(a,()) for a in inits]
    out=ROOT/'private/analysis/boot_phase2'
    header=('/* Generated by tools/lift_boot_phase2.py from the user\'s executable; private. */\n'
            f'#define EXE_SIZE {len(data)}u\n#define EXE_CRC32 0x{zlib.crc32(data):08x}u\n'
            f'#define BOOT_RUNS {len(runs)}u\n'
            'static const struct { uint32_t va; void (*fn)(void); unsigned argc; uint32_t args[2]; } boot_runs[BOOT_RUNS]={\n'+
            ''.join(f'    {{0x{a:x}u,sub_{a:08X},{len(args)}u,{{{",".join(f"0x{x:x}u" for x in args) or "0"}}}}},\n' for a,args in runs)+'};\n'
            '#define BOOT_SLOTS \\\n'+''.join(f'    X({name},0x{slots[name]:x}u) \\\n' for name in APIS)+'\n')
    (out/'boot_phase2_list.h').write_text(header,encoding='utf-8',newline='\n')
    report['runs']=[hex(a) for a,_ in runs]
    (out/'boot_phase2_report.json').write_text(json.dumps(report,indent=2)+'\n',encoding='utf-8')
    x87=sum(1 for i in report['items'] if any('x87' in r or 'float' in r or 'fsqrt' in r or 'fistp' in r for r in i['rewrites']))
    print(len(runs),'runs;',len(report['items']),'functions,',sum(i['instructions'] for i in report['items']),'instructions;',
          x87,'with audited x87 rewrites; imports',sorted(report['imports'].values()))
    print('auto-stopped:',len(report['auto_stopped']));[print(' ',a,why[:140]) for a,why in report['auto_stopped'].items()]
    print('unresolved:',report['unresolved'])
if __name__=='__main__':main()

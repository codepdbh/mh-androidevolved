"""Lift the C++ static initialisers (.CRT) that the port can already run, and their closure.

Phase set, in .CRT order: initialisers whose closure needs no x87, no unsupported
code and, at most, the memory shims (EnterCriticalSection, LeaveCriticalSection,
GlobalAlloc), including those that construct object arrays through indirect calls
(the constructor is passed as a code pointer). Indirect calls go through the
generated fail-closed dispatch table. Also writes a private header with the
initialisers in order and the executable's size and CRC-32.
"""
import json,zlib
from recomp_lift import lift_closure
from inspect_entrypoint import ROOT,GAME
MEMORY_IMPORTS={0x81b3e4:'EnterCriticalSection',0x81b3e8:'LeaveCriticalSection',0x81b40c:'GlobalAlloc'}
def runnable(r):
    return not (r['truncated'] or r['unsupported'] or r['undecoded'] or r['x87']) and set(r['imports'])<=set(MEMORY_IMPORTS.values())
def main():
    results=json.loads((ROOT/'private/analysis/static_initializers.json').read_text(encoding='utf-8'))['results']
    roots=[int(r['initializer'],16) for r in results if runnable(r)]
    report=lift_closure(roots,set(),set(MEMORY_IMPORTS),'static_init',max_functions=800,indirect=True,follow_code_pointers=True,auto_stop=True)
    data=GAME.read_bytes();out=ROOT/'private/analysis/static_init'
    header=('/* Generated by tools/lift_static_init.py from the user\'s executable; private. */\n'
            f'#define EXE_SIZE {len(data)}u\n#define EXE_CRC32 0x{zlib.crc32(data):08x}u\n'
            f'static const uint32_t static_inits[{len(roots)}]={{'+','.join(f'0x{r:x}u' for r in roots)+'};\n'
            f'static void (*const static_init_fns[{len(roots)}])(void)={{'+','.join(f'sub_{r:08X}' for r in roots)+'};\n')
    (out/'static_init_list.h').write_text(header,encoding='utf-8',newline='\n')
    report['initializers']=[hex(r) for r in roots]
    (out/'static_init_report.json').write_text(json.dumps(report,indent=2)+'\n',encoding='utf-8')
    indirect=sum(1 for i in report['items'] for s in i['sites'] if 'indirect' in s)
    print(len(roots),'initialisers;',len(report['items']),'functions,',sum(i['instructions'] for i in report['items']),'instructions;',
          indirect,'indirect call sites;',len(report['code_pointers']),'code pointers; imports',sorted(report['imports'].values()));print('auto-stopped:',report['auto_stopped']);print('unresolved:',report['unresolved'])
if __name__=='__main__':main()

"""Split the translated WinMain unit (private/analysis/winmain/winmain_unit.c) into separately
compiled parts, so that no compiler process needs more memory than the work-safe job limit.

winmain_decls.h holds the declarations of every translated function (included by
runtime/game_runner.c); winmain_unit_part<N>.c each hold a share of the function bodies with the
same runtime headers as game_runner.c. The runtime headers only declare the guest state
(`extern`), so the parts share it. The unit itself is unchanged (its hash stays the lift's).
"""
import re
from pathlib import Path
from inspect_entrypoint import ROOT

PARTS = 8
PREAMBLE = ('/* Generated by tools/split_winmain_unit.py from winmain_unit.c; private. */\n'
            '#define RECOMP_GENERATED_CODE\n#include <stdint.h>\n#include <stddef.h>\n#include <string.h>\n'
            '#include "guest_memory.h"\n#include "recomp_types.h"\n#include "checked_memory_adapter.h"\n'
            '#include "checked_dispatch_adapter.h"\n#include "virtual_cpu.h"\n#include "x87_semantics.h"\n'
            '#include "x86_semantics.h"\n#include "winmain_decls.h"\n'
            'uint64_t mh_guest_rdtsc(void);   /* runtime/game_runner.c: rdtsc reads the port\'s virtual counter */\n')


def split(base=ROOT / 'private/analysis/winmain', parts=PARTS):
    unit = (base / 'winmain_unit.c').read_text(encoding='utf-8')
    starts = [m.start() for m in re.finditer(r'^void sub_[0-9A-F]{8}\(void\) \{$', unit, re.MULTILINE)]
    if not starts:raise SystemExit('no translated functions in the unit')
    decls = unit[:starts[0]]
    if any(line and not re.fullmatch(r'void sub_[0-9A-F]{8}\(void\);', line) for line in decls.splitlines()):
        raise SystemExit('unexpected text before the first function')
    bodies = [unit[a:b] for a, b in zip(starts, starts[1:] + [len(unit)])]
    (base / 'winmain_decls.h').write_text('/* Generated by tools/split_winmain_unit.py; private. */\n#pragma once\n' + decls,
                                          encoding='utf-8', newline='\n')
    total = sum(len(b) for b in bodies); target = total / parts; out = []; cur = []; size = 0
    for body in bodies:
        cur.append(body); size += len(body)
        if size >= target and len(out) < parts - 1:out.append(cur); cur = []; size = 0
    out.append(cur)
    for old in base.glob('winmain_unit_part*.c'):old.unlink()
    for i, chunk in enumerate(out, 1):
        (base / f'winmain_unit_part{i}.c').write_text(PREAMBLE + ''.join(chunk), encoding='utf-8', newline='\n')
    if ''.join(''.join(c) for c in out) != unit[starts[0]:]:raise SystemExit('split lost text')
    return len(out)


if __name__ == '__main__':
    print(split(), 'parts')
